# frozen_string_literal: true

require "fileutils"
require "stringio"
require "gepub"
require "bkr/builder/media_types"
require "bkr/builder/sources"
require "bkr/builder/chapter"

module Bkr
  # Builds a Project into an EPUB 3 file.
  #
  #   path = Bkr::Builder.new(project).build  # => "/path/to/book/build/my_book.epub"
  #
  # Package layout (inside OEBPS/, next to package.opf):
  #   text/01_<chapter>.xhtml   chapters, in reading order
  #   bkr/                      bundled bkr.css / bkr.js
  #   css/ js/ images/ fonts/   mirrors the project's assets/ folder
  #   nav.xhtml, toc.ncx        generated by gepub
  #
  # Raises BuildError (with paths relative to the project root) when a file is
  # missing, a config path leaves the project, or a chapter is not well-formed.
  class Builder
    PACKAGE_PATH = "OEBPS/package.opf"
    UNIQUE_IDENTIFIER_ID = "BookId"
    CHAPTER_DIR = "text"

    def initialize(project)
      @project = project
    end

    # Returns the absolute path of the generated .epub.
    def build
      logger.info("Building #{config.title.inspect} from #{@project.root}")
      sources = Sources.new(@project)
      chapters = load_chapters(sources)
      stylesheets = sources.stylesheets
      scripts = sources.scripts
      cover = sources.cover
      resources = [*stylesheets, *scripts, cover, *sources.media].compact.uniq(&:href)

      book = new_book
      resources.each { |resource| add_resource(book, resource, cover: resource.equal?(cover)) }
      add_chapters(book, chapters, stylesheets: stylesheets, scripts: scripts, links: links_for(chapters, resources))
      write(book, sources)
    end

    private

    def config = @project.config
    def logger = @project.logger

    def load_chapters(sources)
      list = sources.chapters
      width = [2, list.size.to_s.size].max
      list.each_with_index.map do |chapter, index|
        # Drop an existing "01_" style prefix so 01_intro.html doesn't become 01_01_intro.xhtml.
        slug = File.basename(chapter.source, ".*").gsub(/[^A-Za-z0-9_-]+/, "_").sub(/\A\d+[_-]+(?=.)/, "")
        href = format("%<dir>s/%<number>0#{width}d_%<slug>s.xhtml", dir: CHAPTER_DIR, number: index + 1, slug: slug)
        Chapter.new(source: chapter.source, href: href, title: chapter.title,
                    display_path: sources.display(chapter.source))
      end
    end

    def new_book
      book = GEPUB::Book.new(PACKAGE_PATH)
      book.primary_identifier(config.identifier, UNIQUE_IDENTIFIER_ID)
      book.title = config.title
      config.authors.each do |author|
        book.add_creator(author).refine("role", "aut", "scheme" => "marc:relators")
      end
      book.language = config.language
      book.lang = config.language
      add_optional_metadata(book.metadata)
      book
    end

    def add_optional_metadata(metadata)
      { "publisher" => config.publisher, "description" => config.description, "date" => config.date }
        .each do |name, value|
          next unless present?(value)

          metadata.add_metadata(name, name == "date" ? date_string(value) : value.to_s)
        end
    end

    # dc:date must be W3CDTF; keep plain dates as YYYY-MM-DD.
    def date_string(date)
      case date
      when Time then date.utc.iso8601
      when Date then date.iso8601
      else date.to_s.strip
      end
    end

    def present?(value)
      !value.nil? && !value.to_s.strip.empty?
    end

    def add_resource(book, resource, cover: false)
      logger.debug("Adding #{resource.href} (#{resource.media_type})")
      item = book.add_item(resource.href, id: item_id(resource.href), media_type: resource.media_type,
                                          content: resource.source)
      item.cover_image if cover
      item
    end

    def add_chapters(book, chapters, stylesheets:, scripts:, links:)
      logger.info("Adding #{chapters.size} chapter(s)")
      book.ordered do
        chapters.each do |chapter|
          logger.debug("Adding #{chapter.href} from #{chapter.display_path} (#{chapter.title.inspect})")
          xhtml = chapter.to_xhtml(language: config.language, stylesheets: stylesheets, scripts: scripts, links: links)
          item = book.add_item(chapter.href, id: item_id(chapter.href), content: StringIO.new(xhtml),
                                             toc_text: chapter.title)
          item.add_property("scripted") if scripts.any?
        end
      end
    end

    # Absolute source path => package href, for rewriting links inside chapters.
    def links_for(chapters, resources)
      resources.to_h { |res| [res.source, res.href] }.merge(chapters.to_h { |ch| [ch.source, ch.href] })
    end

    # Manifest ids must be unique XML names: derive them from the href.
    def item_id(href)
      @item_ids ||= {}
      base = href.gsub(/[^A-Za-z0-9_-]/, "_")
      id = base
      id = "#{base}_#{@item_ids.size}" while @item_ids.key?(id)
      @item_ids[id] = true
      id
    end

    def write(book, sources)
      path = @project.epub_path
      FileUtils.mkdir_p(File.dirname(path))
      tmp_path = "#{path}.tmp"
      book.generate_epub(tmp_path)
      File.rename(tmp_path, path)
      logger.info("Wrote #{sources.display(path)} (#{File.size(path)} bytes)")
      path
    ensure
      FileUtils.rm_f(tmp_path) if tmp_path
    end
  end
end
